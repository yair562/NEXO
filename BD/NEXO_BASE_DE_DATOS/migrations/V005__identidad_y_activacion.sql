SET LOCAL search_path TO nexo, public;

CREATE TABLE padron_estudiantes (
    matricula VARCHAR(20) PRIMARY KEY,
    nombre VARCHAR(100),
    correo VARCHAR(150) NOT NULL UNIQUE,
    autorizado BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT padron_matricula_formato CHECK (matricula ~ '^[0-9]{1,20}$'),
    CONSTRAINT padron_correo_formato CHECK (
        correo = lower(correo)
        AND correo LIKE 'l%@huixquilucan.tecnm.mx'
    )
);

ALTER TABLE usuarios
    ADD COLUMN matricula VARCHAR(20),
    ADD COLUMN estado TEXT NOT NULL DEFAULT 'ACTIVE',
    ADD COLUMN correo_verificado_en TIMESTAMPTZ,
    ADD COLUMN activado_en TIMESTAMPTZ;

ALTER TABLE usuarios
    ALTER COLUMN contrasena_hash DROP NOT NULL;

ALTER TABLE usuarios
    ADD CONSTRAINT usuarios_matricula_unica UNIQUE (matricula),
    ADD CONSTRAINT usuarios_matricula_formato CHECK (
        matricula IS NULL OR matricula ~ '^[0-9]{1,20}$'
    ),
    ADD CONSTRAINT usuarios_estado_valido CHECK (
        estado IN ('PENDING', 'ACTIVE', 'SUSPENDED', 'INACTIVE')
    );

CREATE TABLE activaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    codigo_hash CHAR(64) NOT NULL UNIQUE,
    expira_en TIMESTAMPTZ NOT NULL,
    intentos SMALLINT NOT NULL DEFAULT 0,
    usado BOOLEAN NOT NULL DEFAULT FALSE,
    verificado_en TIMESTAMPTZ,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT activaciones_intentos_validos CHECK (intentos BETWEEN 0 AND 5)
);

CREATE INDEX activaciones_usuario_idx ON activaciones (usuario_id, creado_en DESC);

GRANT SELECT, INSERT, UPDATE ON padron_estudiantes, activaciones TO nexo_app;
GRANT SELECT, INSERT, UPDATE ON usuarios TO nexo_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA nexo TO nexo_app;
